  def password_text_input(message, max_length, initial = "")
    limit = [[max_length.to_i, 1].max, 32].min
    if defined?(pbMessageFreeText)
      begin
        return pbMessageFreeText(message, initial.to_s, false, limit).to_s
      rescue
        begin
          return pbMessageFreeText(message, initial.to_s, limit).to_s
        rescue
        end
      end
    end
    if defined?(pbEnterText)
      begin
        return pbEnterText(message, 0, limit, initial.to_s).to_s
      rescue
        begin
          return pbEnterText(message, 1, limit, initial.to_s).to_s
        rescue
        end
      end
    end
    ""
  rescue
    ""
  end

  def whismur_unlock_password?(input)
